-- Users -------------------------------------------------------------------
CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_app_users_email UNIQUE (email)
);

-- Job postings discovered by scraper-service (ingested from RabbitMQ) ----
CREATE TABLE job_postings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source        VARCHAR(32)   NOT NULL,
    company       VARCHAR(255)  NOT NULL,
    external_id   VARCHAR(255)  NOT NULL,
    title         VARCHAR(500)  NOT NULL,
    location      VARCHAR(500),
    url           VARCHAR(2048) NOT NULL,
    posted_at     TIMESTAMP WITH TIME ZONE,
    discovered_at TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Idempotency key: redelivered or duplicated events can never create a second row.
    CONSTRAINT uq_job_postings_source_company_ext UNIQUE (source, company, external_id)
);
CREATE INDEX ix_job_postings_discovered_at ON job_postings (discovered_at DESC);
CREATE INDEX ix_job_postings_company ON job_postings (company);

-- A user's application pipeline (Kanban cards) ----------------------------
CREATE TABLE job_applications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    job_id      BIGINT        REFERENCES job_postings (id) ON DELETE SET NULL,
    company     VARCHAR(255)  NOT NULL,
    role_title  VARCHAR(500)  NOT NULL,
    url         VARCHAR(2048),
    location    VARCHAR(500),
    status      VARCHAR(32)   NOT NULL,
    position    INTEGER       NOT NULL,
    notes       VARCHAR(4000),
    applied_at  TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_job_applications_user_job UNIQUE (user_id, job_id)
);
CREATE INDEX ix_job_applications_board ON job_applications (user_id, status, position);
